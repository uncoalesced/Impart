#!/usr/bin/env python3
"""Generate the Impart mark: a pointer arrowhead on the uncoalesced 9x9 grid.

Impart's accent is Watermelon (#EF2D56). The mark follows the family rules in
tokens.json: circles and rounded squares on a 9x9 grid, a shade/base/tint ramp
of one hue, and the center cell (4, 4) always empty. Stdlib only.

The shipped mark is seed 4. Regenerating with that seed is byte-for-byte stable.

Usage:
  python impart_mark.py --seed 4 --out-dir .
  python impart_mark.py --seed 4 --out-dir . --android ../app/src/main/res/drawable

Outputs:
  impart-mark.svg              mark on the graphite ground
  impart-mark-transparent.svg  mark alone
  impart-mark.cells.json       the fixed cell list (row, col, shape, color) that
                               the app draws in Compose; never randomize at runtime
  with --android: ic_launcher_foreground.xml, ic_launcher_background.xml,
                  ic_launcher_monochrome.xml, ic_stat_impart.xml
"""
import argparse
import json
import math
import random
from pathlib import Path

GRAPHITE, PORCELAIN, WATERMELON = "#333333", "#FDFFFC", "#EF2D56"
GRID, CANVAS = 9, 900
CIRCLE_P, CIRCLE_D, SQUARE_S, SQUARE_R = 0.63, 0.62, 0.66, 0.12


def mix(a, b, t):
    pa = [int(a[i:i + 2], 16) for i in (1, 3, 5)]
    pb = [int(b[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x + (y - x) * t):02X}" for x, y in zip(pa, pb))


RAMP = {
    "shade": mix(WATERMELON, GRAPHITE, 0.35),
    "base": WATERMELON,
    "tint": mix(WATERMELON, PORCELAIN, 0.35),
}
WEIGHTS = [("shade", 0.25), ("base", 0.5), ("tint", 0.25)]


def _tri(p, a, b, c):
    def s(p1, p2, p3):
        return (p1[0] - p3[0]) * (p2[1] - p3[1]) - (p2[0] - p3[0]) * (p1[1] - p3[1])
    d1, d2, d3 = s(p, a, b), s(p, b, c), s(p, c, a)
    return not ((d1 < 0 or d2 < 0 or d3 < 0) and (d1 > 0 or d2 > 0 or d3 > 0))


def inside(x, y):
    """Arrowhead pointing up with a notched base. Units are grid cells."""
    apex, left, right, notch = (4.5, 0.2), (0.6, 8.6), (8.4, 8.6), (4.5, 6.2)
    if math.hypot(x - 4.5, y - 4.5) < 0.6:
        return False  # the center never coalesces
    return _tri((x, y), apex, left, right) and not _tri((x, y), left, right, notch)


def generate(seed):
    rng = random.Random(seed)
    tones, w = zip(*WEIGHTS)
    cells = []
    for r in range(GRID):
        for c in range(GRID):
            if inside(c + 0.5, r + 0.5):
                shape = "circle" if rng.random() < CIRCLE_P else "square"
                tone = rng.choices(tones, weights=w)[0]
                cells.append({"row": r, "col": c, "shape": shape, "tone": tone, "color": RAMP[tone]})
    assert not any(k["row"] == 4 and k["col"] == 4 for k in cells), "center cell filled"
    return cells


def svg(cells, ground):
    cell = CANVAS / GRID
    out = [f'<svg viewBox="0 0 {CANVAS} {CANVAS}" xmlns="http://www.w3.org/2000/svg">']
    if ground:
        out.append(f'<rect width="{CANVAS}" height="{CANVAS}" fill="{GRAPHITE}"/>')
    for k in cells:
        cx, cy = k["col"] * cell + cell / 2, k["row"] * cell + cell / 2
        if k["shape"] == "circle":
            out.append(f'<circle cx="{cx:.1f}" cy="{cy:.1f}" r="{cell * CIRCLE_D / 2:.1f}" fill="{k["color"]}"/>')
        else:
            side = cell * SQUARE_S
            out.append(f'<rect x="{cx - side / 2:.1f}" y="{cy - side / 2:.1f}" width="{side:.1f}" '
                       f'height="{side:.1f}" rx="{side * SQUARE_R:.1f}" fill="{k["color"]}"/>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


def _f(v):
    return f"{v:.3f}".rstrip("0").rstrip(".")


def path_for(k, size, offset):
    """VectorDrawable path data for one cell inside a size x size box at offset."""
    cell = size / GRID
    cx, cy = offset + k["col"] * cell + cell / 2, offset + k["row"] * cell + cell / 2
    if k["shape"] == "circle":
        r = cell * CIRCLE_D / 2
        return (f"M{_f(cx - r)},{_f(cy)} a{_f(r)},{_f(r)} 0 1,0 {_f(2 * r)},0 "
                f"a{_f(r)},{_f(r)} 0 1,0 {_f(-2 * r)},0 Z")
    s = cell * SQUARE_S
    q = s * SQUARE_R
    x, y = cx - s / 2, cy - s / 2
    e = s - 2 * q
    return (f"M{_f(x + q)},{_f(y)} h{_f(e)} a{_f(q)},{_f(q)} 0 0,1 {_f(q)},{_f(q)} v{_f(e)} "
            f"a{_f(q)},{_f(q)} 0 0,1 {_f(-q)},{_f(q)} h{_f(-e)} a{_f(q)},{_f(q)} 0 0,1 {_f(-q)},{_f(-q)} "
            f"v{_f(-e)} a{_f(q)},{_f(q)} 0 0,1 {_f(q)},{_f(-q)} Z")


HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by design/impart_mark.py. Do not edit by hand. -->\n'


def vector(paths, dp, viewport):
    body = "".join(f'    <path\n        android:fillColor="{c}"\n        android:pathData="{d}" />\n'
                   for c, d in paths)
    return (HEADER + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{dp}dp"\n    android:height="{dp}dp"\n'
            f'    android:viewportWidth="{viewport}"\n    android:viewportHeight="{viewport}">\n'
            + body + "</vector>\n")


def android(cells, out):
    # Adaptive icon: 108 canvas, 72 visible, 66 safe circle. The arrow's base
    # corners sit 0.63 of the side from center, so a 52-unit box keeps them inside.
    size, off = 52.0, 28.0
    by_color = {}
    for k in cells:
        by_color.setdefault(k["color"], []).append(path_for(k, size, off))
    fg = [("#FF" + c[1:], " ".join(p)) for c, p in by_color.items()]
    mono = [("#FFFFFFFF", " ".join(path_for(k, size, off) for k in cells))]
    (out / "ic_launcher_foreground.xml").write_text(vector(fg, 108, 108))
    (out / "ic_launcher_monochrome.xml").write_text(vector(mono, 108, 108))
    (out / "ic_launcher_background.xml").write_text(
        vector([("#FF" + GRAPHITE[1:], "M0,0 h108 v108 h-108 Z")], 108, 108))
    # Status bar icon: 24dp, white only (the system tints it), 20-unit box.
    stat = [("#FFFFFFFF", " ".join(path_for(k, 20.0, 2.0) for k in cells))]
    (out / "ic_stat_impart.xml").write_text(vector(stat, 24, 24))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=4)
    ap.add_argument("--out-dir", default=".")
    ap.add_argument("--android", help="drawable directory to write vector resources into")
    a = ap.parse_args()
    cells = generate(a.seed)
    out = Path(a.out_dir)
    (out / "impart-mark.svg").write_text(svg(cells, True))
    (out / "impart-mark-transparent.svg").write_text(svg(cells, False))
    (out / "impart-mark.cells.json").write_text(json.dumps(
        {"grid": GRID, "seed": a.seed, "center_empty": [4, 4], "ramp": RAMP, "cells": cells}, indent=2) + "\n")
    if a.android:
        android(cells, Path(a.android))
    print(f"wrote mark: {len(cells)} cells, seed {a.seed}")


if __name__ == "__main__":
    main()
